const router=require('express').Router();
const controller=require('../controllers/internalAssetController');
const {verifyToken,requirePermission}=require('../middleware/authMiddleware');
const {requireInternalScope,canReadInternal}=require('../services/internalAssetService');
const {internalUpload}=require('../middleware/internalUpload');
const {ensureUploadCapacity}=require('../config/storage');
const {writeLimiter}=require('../middleware/security');

router.use((_req,res,next)=>{res.setHeader('Cache-Control','private, no-store');next();});
router.use(verifyToken);
router.get('/context',controller.getContext);
router.use(requireInternalScope);
router.get('/options',(req,res,next)=>canReadInternal(req.internalScope.subject)?next():res.status(403).json({error:'Akses data internal tidak diizinkan.'}),controller.getOptions);
router.get('/types',requirePermission('internal_data_types','view'),controller.listTypes);
router.post('/types',writeLimiter,requirePermission('internal_data_types','view'),requirePermission('internal_data_types','post'),controller.saveType);
router.put('/types/:id',writeLimiter,requirePermission('internal_data_types','view'),requirePermission('internal_data_types','edit'),controller.saveType);
router.delete('/types/:id',writeLimiter,requirePermission('internal_data_types','view'),requirePermission('internal_data_types','delete'),controller.deleteType);
router.get('/categories',requirePermission('internal_data_categories','view'),controller.listCategories);
router.post('/categories',writeLimiter,requirePermission('internal_data_categories','view'),requirePermission('internal_data_categories','post'),controller.saveCategory);
router.put('/categories/:id',writeLimiter,requirePermission('internal_data_categories','view'),requirePermission('internal_data_categories','edit'),controller.saveCategory);
router.delete('/categories/:id',writeLimiter,requirePermission('internal_data_categories','view'),requirePermission('internal_data_categories','delete'),controller.deleteCategory);
router.get('/recovery',requirePermission('internal_asset_recovery','view'),controller.listDeletions);
router.delete('/recovery/:deletionId',writeLimiter,requirePermission('internal_asset_recovery','view'),requirePermission('internal_asset_recovery','delete'),controller.permanentlyDeleteAsset);
router.post('/:id/restore',writeLimiter,requirePermission('internal_asset_recovery','view'),requirePermission('internal_asset_recovery','edit'),controller.restoreAsset);
router.use(requirePermission('internal_assets','view'));
router.get('/',controller.listAssets);
router.post('/',writeLimiter,requirePermission('internal_assets','post'),ensureUploadCapacity,internalUpload,controller.createAsset);
router.get('/:id',controller.getAsset);
router.put('/:id',writeLimiter,requirePermission('internal_assets','edit'),controller.checkEditAccess,ensureUploadCapacity,internalUpload,controller.updateAsset);
router.delete('/:id',writeLimiter,requirePermission('internal_assets','delete'),controller.deleteAsset);
router.get('/:id/download',controller.downloadZip);
router.get('/:id/files/:fileId/file',controller.getFile);
router.get('/:id/files/:fileId/preview',controller.getPreview);
router.get('/:id/files/:fileId/preview/pdf',controller.getPreviewPdf);
router.get('/:id/file',controller.getFile);
router.get('/:id/preview',controller.getPreview);
module.exports=router;
